// Bundles textures/*.json into maker/library.js so the maker can open them from disk (no server).
// Run after adding or editing textures by hand: node maker/build-library.mjs
import fs from "fs";
import path from "path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const lib = {};
for (const f of fs.readdirSync(path.join(root, "textures")).sort()) {
  if (f.endsWith(".json")) lib[f.replace(".json", "")] = JSON.parse(fs.readFileSync(path.join(root, "textures", f), "utf8"));
}
fs.writeFileSync(path.join(root, "maker/library.js"), "// Generated by build-library.mjs from textures/*.json. Do not edit.\nwindow.TEX_LIBRARY = " + JSON.stringify(lib, null, 1) + ";\n");
console.log("library:", Object.keys(lib).length, "textures");
